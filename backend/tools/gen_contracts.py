"""Generate Pydantic v2 models and TypeScript types from the canonical JSON Schemas (ADR-037).

contracts/domain/v1/*.schema.json is the only source of truth. Outputs:
  backend/packages/domain/src/aiagent_domain/generated.py
  web/src/api/generated/domain.ts
`--check` fails (exit 1) when the committed outputs differ from what the schemas produce (CI gate: diff 0).

Supported subset (anything else is a generator error, never silently approximated): object with
additionalProperties=false, string (pattern/minLength/maxLength/enum/const), int64 decimal strings ($defs with
x-int64), integer (min/max), boolean, generic JSON object, $ref, anyOf[X, null].
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "contracts" / "domain" / "v1"
PY_OUT = ROOT / "backend" / "packages" / "domain" / "src" / "aiagent_domain" / "generated.py"
TS_OUT = ROOT / "web" / "src" / "api" / "generated" / "domain.ts"
INT64_TYPES = {"Int64", "NonNegativeInt64", "PositiveInt64"}


class GenError(Exception):
    pass


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def load() -> tuple[dict[str, Any], list[tuple[str, dict[str, Any]]]]:
    common = json.loads((SCHEMA_DIR / "common.schema.json").read_text(encoding="utf-8"))
    entities = []
    for p in sorted(SCHEMA_DIR.glob("*.schema.json")):
        if p.name == "common.schema.json":
            continue
        entities.append((p.name, json.loads(p.read_text(encoding="utf-8"))))
    return common["$defs"], entities


def ref_name(ref: str) -> str:
    m = re.fullmatch(r"(?:common\.schema\.json)?#/\$defs/([A-Za-z0-9]+)", ref)
    if not m:
        raise GenError(f"unsupported $ref {ref}")
    return m.group(1)


def py_str(s: dict[str, Any]) -> str:
    if "const" in s:
        return f"Literal[{json.dumps(s['const'])}]"
    if "enum" in s:
        return "Literal[" + ", ".join(json.dumps(v) for v in s["enum"]) + "]"
    args = []
    if "pattern" in s:
        args.append(f"pattern={s['pattern']!r}")
    if "minLength" in s:
        args.append(f"min_length={s['minLength']}")
    if "maxLength" in s:
        args.append(f"max_length={s['maxLength']}")
    return f"Annotated[str, StringConstraints({', '.join(args)})]" if args else "str"


def py_type(s: dict[str, Any], inline_objects: dict[str, str]) -> str:
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "anyOf" in s:
        opts = s["anyOf"]
        if len(opts) != 2 or opts[1] != {"type": "null"}:
            raise GenError("only anyOf [X, null] is supported")
        return f"{py_type(opts[0], inline_objects)} | None"
    t = s.get("type")
    if t == "string":
        return py_str(s)
    if t == "boolean":
        return "bool"
    if t == "integer":
        lo, hi = s.get("minimum"), s.get("maximum")
        if lo is None or hi is None or hi > 2**31:
            raise GenError("plain integers must be bounded (<= 2^31); use an int64 $def for larger values")
        return f"Annotated[int, Field(ge={lo}, le={hi})]"
    if t == "object" and "properties" not in s:
        return "dict[str, Any]"
    raise GenError(f"unsupported schema {s}")


def gen_model(name: str, s: dict[str, Any], doc: str | None) -> str:
    if s.get("type") != "object" or s.get("additionalProperties") is not False:
        raise GenError(f"{name}: objects must set additionalProperties=false")
    req = set(s.get("required", []))
    lines = [f"class {name}(_Contract):"]
    if doc:
        lines.append(f"    {json.dumps(doc, ensure_ascii=False)}")
    lines.append(f"    __schema_title__: ClassVar[str] = {json.dumps(s.get('title', name))}")
    for prop, ps in s["properties"].items():
        t = py_type(ps, {})
        default = ""
        if prop not in req:
            if not t.endswith("| None"):
                raise GenError(f"{name}.{prop}: optional fields must be nullable")
            default = " = None"
        alias = f'Field(alias="{prop}")' if snake(prop) != prop else None
        if alias and default:
            lines.append(f"    {snake(prop)}: Annotated[{t}, {alias}]{default}")
        elif alias:
            lines.append(f"    {snake(prop)}: Annotated[{t}, {alias}]")
        else:
            lines.append(f"    {snake(prop)}: {t}{default}")
    return "\n".join(lines)


def gen_py(defs: dict[str, Any], entities: list[tuple[str, dict[str, Any]]]) -> str:
    out = [
        '"""GENERATED by backend/tools/gen_contracts.py from contracts/domain/v1 - DO NOT EDIT.',
        "",
        "Canonical source: contracts/domain/v1/*.schema.json (ADR-037). Regenerate with",
        "`uv run python tools/gen_contracts.py`; CI fails when this file differs from the schemas.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Any, ClassVar, Literal",
        "",
        "from pydantic import BaseModel, ConfigDict, Field, StringConstraints",
        "",
        "from .int64 import Int64, NonNegativeInt64, PositiveInt64",
        "",
        '__all__ = ["Int64", "NonNegativeInt64", "PositiveInt64"]',
        "",
        "",
        "class _Contract(BaseModel):",
        '    """strict, unknown fields rejected, immutable, camelCase on the wire."""',
        "",
        "    model_config = ConfigDict(",
        '        strict=True, extra="forbid", frozen=True, validate_by_name=True, validate_by_alias=True,',
        "        serialize_by_alias=True,",
        "    )",
        "",
    ]
    for dname, ds in defs.items():
        if dname in INT64_TYPES:
            continue
        if ds.get("type") == "object" and "properties" in ds:
            out += ["", gen_model(dname, ds, ds.get("description")), ""]
        else:
            out.append(f"{dname} = {py_type(ds, {})}")
    out.append("")
    titles = []
    for fname, s in entities:
        title = s["title"]
        titles.append((title, fname))
        out += ["", gen_model(title, s, s.get("description")), ""]
    out += ["", "SCHEMA_FILES: dict[str, str] = {"]
    out += [f'    "{t}": "{f}",' for t, f in titles]
    out += ["}", ""]
    out += ["MODELS: dict[str, type[_Contract]] = {"]
    out += [f'    "{t}": {t},' for t, _ in titles]
    out += ["}", ""]
    return "\n".join(out)


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "anyOf" in s:
        return f"{ts_type(s['anyOf'][0])} | null"
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    t = s.get("type")
    return {"string": "string", "boolean": "boolean", "integer": "number"}.get(
        t, "Readonly<Record<string, unknown>>" if t == "object" else "never"
    )


def gen_ts(defs: dict[str, Any], entities: list[tuple[str, dict[str, Any]]]) -> str:
    out = [
        "// GENERATED by backend/tools/gen_contracts.py from contracts/domain/v1 - DO NOT EDIT.",
        "// int64 fields are canonical decimal strings: decode with BigInt, never Number.",
        "",
    ]
    for dname, ds in defs.items():
        if ds.get("type") == "object" and "properties" in ds:
            out.append(f"export interface {dname} {{")
            for p, ps in ds["properties"].items():
                out.append(f"  readonly {p}: {ts_type(ps)};")
            out.append("}")
        else:
            out.append(f"export type {dname} = {ts_type(ds) if dname not in INT64_TYPES else 'string'};")
    for _, s in entities:
        req = set(s.get("required", []))
        out += ["", f"export interface {s['title']} {{"]
        for p, ps in s["properties"].items():
            out.append(f"  readonly {p}{'' if p in req else '?'}: {ts_type(ps)};")
        out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    defs, entities = load()
    py, ts = gen_py(defs, entities), gen_ts(defs, entities)
    if "--check" in sys.argv:
        bad = [p for p, c in ((PY_OUT, py), (TS_OUT, ts)) if not p.exists() or p.read_text(encoding="utf-8") != c]
        for p in bad:
            print(f"generated file out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if bad else 0
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.write_text(py, encoding="utf-8", newline="\n")
    TS_OUT.write_text(ts, encoding="utf-8", newline="\n")
    print(f"wrote {PY_OUT.relative_to(ROOT)} and {TS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
